import { readFileSync } from "node:fs";
import ts from "typescript";

const source = readFileSync(new URL("../src/data/blogPosts.ts", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
});
const { blogPosts } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
const rows = blogPosts.map(({ id, title, excerpt, category, date, readTime, tags, sections }) => ({
  slug: id, title, excerpt, category, date, read_time: readTime, tags, sections,
}));
const json = JSON.stringify(rows, null, 2);
if (json.includes("$legacy_blog$")) throw new Error("Unexpected SQL delimiter in seed");
console.log(`-- Generated by node scripts/generate-blog-seed.mjs. Preserves all existing slugs and article bodies.
insert into public.blog_posts (slug, title, excerpt, category, date, read_time, tags, sections, source, status)
select slug, title, excerpt, category, date, read_time, tags, sections, 'legacy', 'published'
from jsonb_to_recordset($legacy_blog$${json}$legacy_blog$::jsonb)
  as seed(slug text, title text, excerpt text, category text, date date, read_time text, tags text[], sections jsonb)
on conflict (slug) do nothing;`);
